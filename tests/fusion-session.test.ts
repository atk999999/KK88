import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import { db } from '../story/db';
import { GeminiService } from '../story/services/geminiService';
import { GameGenre, type GameSession } from '../story/types';
const card = {id:'card-test',name:'Mô bản thử',description:'Huyết thống dung hợp',personality:'Điềm tĩnh; bảo vệ đồng đội; nói ngắn gọn.',imageUrl:'data:image/png;base64,test',level:10,powerLevel:1000};
const session: GameSession = {heroName:'Tên riêng',gender:'Nam',genre:GameGenre.FANTASY,createdAt:Date.now(),nsfwIntensity:'soft',avatarUrl:card.imageUrl,worldSettings:{worldContext:'Thế giới thử',plotDirection:'Khám phá',majorFactions:'',keyNpcs:'',fusionTemplate:structuredClone(card)},characterTraits:{spiritualRoot:'Dung hợp',talents:[],personality:card.personality}};
const id = await db.importSession(session, []);
card.personality = 'Đã đổi trên thẻ gốc';
const saved = await db.sessions.get(id);
assert(saved);
assert.notEqual(saved.worldSettings.fusionTemplate?.personality,card.personality);
const restoredId = await db.importSession(JSON.parse(JSON.stringify(saved)), []);
const restored = await db.sessions.get(restoredId);
assert.equal(restored?.worldSettings.fusionTemplate?.personality,session.characterTraits?.personality);
assert.equal(restored?.avatarUrl,card.imageUrl);
const service = new GeminiService();
const prompt = (service as any).buildSystemPrompt(saved.genre,saved.heroName,saved.gender,saved.worldSettings,saved.characterTraits);
assert(prompt.includes(saved.worldSettings.fusionTemplate!.personality));
assert(prompt.includes('Người chơi quyết định hành động quan trọng'));
assert(!prompt.includes(card.imageUrl));
await db.delete();
console.log('PASS: snapshot độc lập, lưu/nhập lại hồ sơ + ảnh + tính cách, prompt giữ tính cách và quyền lựa chọn; không gọi API.');
